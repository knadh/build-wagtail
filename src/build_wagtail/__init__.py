"""Turn a wagtail project into a Dockerised setup for deployment instantly."""

import argparse
import json
import os
import re
import secrets
import subprocess
import sys
from pathlib import Path, PurePosixPath

MARKER = "# Generated by build-wagtail"

# Files in the project relative to its root.
MANAGE_PY = Path("manage.py")
PYTHON_VERSION_FILE = Path(".python-version")

# Files that this script writes into the project.
GEN = Path(".wagtail-docker")
ENV_FILE = Path(".env")
COMPOSE_FILE = Path("compose.yml")

# Paths and names inside the containers. The project is mounted at APP_DIR, and
# the image only has Python and the dependencies in VENV_DIR.
APP_DIR = PurePosixPath("/app")
VENV_DIR = "/venv"
APP_PORT = 8000
SETTINGS_MODULE = "wagtail_docker_settings"

UV_IMAGE = "ghcr.io/astral-sh/uv:python{python}-bookworm-slim"

DEFAULT_PORT = 8000
DEFAULT_WORKERS = 3
DEFAULT_THREADS = 4
DEFAULT_PYTHON = "3.13"

# Wagtail's project template defaults.
DEFAULT_STATIC_ROOT = APP_DIR / "static"
DEFAULT_MEDIA_ROOT = APP_DIR / "media"

DEP_INSTALLERS = [
    ("uv.lock", "COPY pyproject.toml uv.lock ./\nRUN uv sync --frozen --no-dev --no-install-project"),
    ("pyproject.toml", "COPY pyproject.toml ./\nRUN uv sync --no-dev --no-install-project"),
    ("requirements.txt", f"COPY requirements.txt ./\nRUN uv venv {VENV_DIR} && uv pip install -r requirements.txt"),
]


def die(msg):
    sys.exit(f"error: {msg}")


def parse_args():
    p = argparse.ArgumentParser(description="Dockerise a Wagtail project in place to instantly deploy it. Run from the project root.")
    p.add_argument("hosts", nargs="?",
                   help="comma-separated hostnames (first one sohuld be canonical). Required on the first run.")
    p.add_argument("--port", type=int, default=DEFAULT_PORT, help="localhost port the site is served on (default: %(default)s)")
    p.add_argument("--caddy", action="store_true",
                   help="run Caddy in a container and serve wagtail app behind it")
    p.add_argument("--caddy-image", default="caddy:2.10-alpine",
                   help="Caddy image to use with --caddy (default: %(default)s)")
    p.add_argument("--workers", type=int, default=DEFAULT_WORKERS, help="granian workers (default: %(default)s)")
    p.add_argument("--threads", type=int, default=DEFAULT_THREADS,
                   help="granian threads per worker that run the app (default: %(default)s)")
    p.add_argument("--python", help=f"Python version (default: {PYTHON_VERSION_FILE}, else {DEFAULT_PYTHON})")
    p.add_argument("--settings",
                   help="settings module to build on (default: from manage.py, or <project>.settings.production)")
    p.add_argument("--no-build", action="store_true", help="write the files but don't run docker compose build")
    args = p.parse_args()

    if not 0 < args.port < 65536:
        p.error("--port must be between 1 and 65535.")
    if args.workers < 1:
        p.error("--workers must be at least 1.")
    if args.threads < 1:
        p.error("--threads must be at least 1.")
    return args


def find_settings(override):
    """Return (project package, settings module to build on)."""
    m = re.search(r"""DJANGO_SETTINGS_MODULE["'],\s*["']([^"']+)["']""", MANAGE_PY.read_text())
    if not m:
        die(f"couldn't find DJANGO_SETTINGS_MODULE in {MANAGE_PY}.")

    settings = m.group(1)
    project = settings.split(".")[0]
    if not Path(project, "wsgi.py").is_file():
        die(f"{project}/wsgi.py not found.")

    if override:
        return project, override
    if Path(project, "settings", "production.py").is_file():
        settings = f"{project}.settings.production"
    return project, settings


def find_python(override):
    if override:
        return override
    if PYTHON_VERSION_FILE.is_file():
        return PYTHON_VERSION_FILE.read_text().split()[0]
    return DEFAULT_PYTHON


def deps_step():
    """Return the Dockerfile lines that install the project's dependencies."""
    for name, step in DEP_INSTALLERS:
        if Path(name).is_file():
            return step
    die(f"none of {', '.join(n for n, _ in DEP_INSTALLERS)} found.")


def read_env():
    env = {}
    for line in ENV_FILE.read_text().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            env[k.strip()] = v.strip()
    return env


def create_env(hosts):
    # The container runs as the project's owner, so it can write to the
    # database, media and static files there.
    st = Path(".").stat()
    if st.st_uid == 0:
        print("warning: the project is owned by root, so the container will run as root.")

    body = (
        f"DJANGO_SECRET_KEY={secrets.token_urlsafe(50)}\n"
        "# Comma-separated. The first one is canonical.\n"
        f"DJANGO_ALLOWED_HOSTS={hosts}\n"
        f"PUID={st.st_uid}\n"
        f"PGID={st.st_gid}\n"
    )
    fd = os.open(ENV_FILE, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(body)
    print(f"Created {ENV_FILE}")


def update_env_hosts(hosts):
    text = ENV_FILE.read_text()
    new, n = re.subn(r"(?m)^DJANGO_ALLOWED_HOSTS=.*$", lambda _: f"DJANGO_ALLOWED_HOSTS={hosts}", text)
    if n == 0:
        new = text.rstrip("\n") + f"\nDJANGO_ALLOWED_HOSTS={hosts}\n"
    if new != text:
        ENV_FILE.write_text(new)
        print(f"Updated DJANGO_ALLOWED_HOSTS in {ENV_FILE}")


def read_roots():
    """Return the project's STATIC_ROOT and MEDIA_ROOT as seen inside the container."""
    code = "from django.conf import settings as s; print(s.STATIC_ROOT); print(s.MEDIA_ROOT)"
    r = subprocess.run(["docker", "compose", "run", "--rm", "--no-deps", "-T", "web", "python", "-c", code],
                       capture_output=True, text=True)
    if r.returncode != 0:
        die(f"couldn't read STATIC_ROOT and MEDIA_ROOT from the settings:\n{r.stderr}")

    roots = [PurePosixPath(p) for p in r.stdout.strip().splitlines()[-2:]]
    for name, p in zip(["STATIC_ROOT", "MEDIA_ROOT"], roots):
        if APP_DIR not in p.parents:
            die(f"{name} is {p}, outside the project. It has to be inside the project directory.")
    return roots


def settings_py(settings):
    return f'''{MARKER}. Docker overrides on top of the project's own settings.
import os

from {settings} import *  # noqa: F401,F403

DEBUG = False
SECRET_KEY = os.environ["DJANGO_SECRET_KEY"]

ALLOWED_HOSTS = os.environ["DJANGO_ALLOWED_HOSTS"].split(",")
CSRF_TRUSTED_ORIGINS = [f"https://{{h}}" for h in ALLOWED_HOSTS]
WAGTAILADMIN_BASE_URL = f"https://{{ALLOWED_HOSTS[0]}}"

# The port is only published on localhost, so allow previewing the site there.
ALLOWED_HOSTS += ["localhost", "127.0.0.1"]

# TLS is terminated by the reverse proxy in front.
SECURE_PROXY_SSL_HEADER = ("HTTP_X_FORWARDED_PROTO", "https")
SESSION_COOKIE_SECURE = True
CSRF_COOKIE_SECURE = True
'''


def dockerfile(python, deps):
    return f'''{MARKER}.
# Only Python and deps. The project itself is mounted at {APP_DIR}.
FROM {UV_IMAGE.format(python=python)}

ENV UV_COMPILE_BYTECODE=1 \\
    UV_PROJECT_ENVIRONMENT={VENV_DIR} \\
    PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    VIRTUAL_ENV={VENV_DIR} \\
    PATH="{VENV_DIR}/bin:$PATH" \\
    PYTHONPATH={APP_DIR}:{APP_DIR / GEN} \\
    DJANGO_SETTINGS_MODULE={SETTINGS_MODULE}

WORKDIR /deps
{deps}
RUN python -c "import granian" 2>/dev/null || uv pip install granian

WORKDIR {APP_DIR}
EXPOSE {APP_PORT}
'''


def start_command(project, workers, threads, static_root, media_root):
    """Return the web container's command. granian serves /static and /media."""
    return " && ".join([
        f"mkdir -p {media_root}",
        "python manage.py migrate --noinput",
        "python manage.py collectstatic --noinput",
        f"exec granian --interface wsgi {project}.wsgi:application --host 0.0.0.0 --port {APP_PORT}"
        f" --workers {workers} --blocking-threads {threads}"
        f" --static-path-route /static --static-path-mount {static_root}"
        f" --static-path-route /media --static-path-mount {media_root}",
    ])


# BuildKit picks up <Dockerfile>.dockerignore next to the Dockerfile.
# The build only needs the dependency files.
DOCKERIGNORE = "*\n" + "".join(f"!{name}\n" for name, _ in DEP_INSTALLERS)


def caddyfile(static_root, media_root):
    return f"""{MARKER}.
{{
	admin off
	# Pass through X-Forwarded-Proto from the host's reverse proxy.
	servers {{
		trusted_proxies static private_ranges
	}}
}}

:80 {{
	encode zstd gzip

	handle_path /static/* {{
		root * {static_root}
		header Cache-Control "public, max-age=31536000, immutable"
		file_server
	}}
	handle_path /media/* {{
		root * {media_root}
		file_server
	}}
	handle {{
		reverse_proxy web:{APP_PORT}
	}}
}}
"""


def compose(port, caddy_image, command):
    ports = f"""    ports:
      - "127.0.0.1:{port}:{{}}"
"""
    out = f"""{MARKER}. Re-run build-wagtail to change this file; secrets and hosts are in {ENV_FILE}.
services:
  web:
    build:
      context: .
      dockerfile: {GEN}/Dockerfile
    restart: unless-stopped
    env_file: {ENV_FILE}
    user: "${{PUID}}:${{PGID}}"
    volumes:
      - .:{APP_DIR}
    command: {json.dumps(["sh", "-c", command])}
"""
    if not caddy_image:
        return out + ports.format(APP_PORT)

    return out + f"""
  # Serves /static and /media, proxies the rest to granian.
  caddy:
    image: {caddy_image}
    restart: unless-stopped
    depends_on: [web]
{ports.format(80)}    volumes:
      - ./{GEN}/Caddyfile:/etc/caddy/Caddyfile:ro
      - .:{APP_DIR}:ro
"""


def write_compose(args, project, static_root, media_root):
    command = start_command(project, args.workers, args.threads, static_root, media_root)
    COMPOSE_FILE.write_text(compose(args.port, args.caddy_image if args.caddy else None, command))
    if args.caddy:
        (GEN / "Caddyfile").write_text(caddyfile(static_root, media_root))


def main():
    args = parse_args()

    if not MANAGE_PY.is_file():
        die(f"{MANAGE_PY} not found. Run this from the Wagtail project root.")
    if not args.no_build and subprocess.run(["docker", "compose", "version"], capture_output=True).returncode != 0:
        die("docker compose is not available.")
    if COMPOSE_FILE.exists() and not COMPOSE_FILE.read_text().startswith(MARKER):
        die(f"{COMPOSE_FILE} exists and wasn't generated by this script. Move it aside first.")

    project, settings = find_settings(args.settings)
    python = find_python(args.python)
    deps = deps_step()

    if not ENV_FILE.exists():
        if not args.hosts:
            die("first run needs the site's hostnames, e.g. build-wagtail example.org,www.example.org")
        create_env(args.hosts)
    elif args.hosts:
        update_env_hosts(args.hosts)
    env = read_env()

    GEN.mkdir(exist_ok=True)
    (GEN / f"{SETTINGS_MODULE}.py").write_text(settings_py(settings))
    (GEN / "Dockerfile").write_text(dockerfile(python, deps))
    (GEN / "Dockerfile.dockerignore").write_text(DOCKERIGNORE)

    # Written first with Wagtail's default paths for the build. Then again with the project's real ones.
    write_compose(args, project, DEFAULT_STATIC_ROOT, DEFAULT_MEDIA_ROOT)
    if args.no_build:
        print(f"Skipping build. Assuming STATIC_ROOT = {DEFAULT_STATIC_ROOT} and MEDIA_ROOT = {DEFAULT_MEDIA_ROOT}.")
    else:
        if subprocess.run(["docker", "compose", "build"]).returncode != 0:
            die("docker compose build failed.")
        write_compose(args, project, *read_roots())

    print(f"Wrote {COMPOSE_FILE} and {GEN}/ (project: {project}, settings: {settings}, "
          f"python: {python}, caddy: {'yes' if args.caddy else 'no'})")

    host = env["DJANGO_ALLOWED_HOSTS"].split(",")[0]
    print(f"""
Done. Start with:   docker compose up -d
Stop with:          docker compose down
Create admin user:  docker compose exec web python manage.py createsuperuser

The site runs from the files in this directory. After changing code, run
`docker compose restart web`. After changing dependencies, re-run build-wagtail.

The site is on 127.0.0.1:{args.port}.

  {host} {{
      reverse_proxy 127.0.0.1:{args.port}
  }}""")


if __name__ == "__main__":
    main()
